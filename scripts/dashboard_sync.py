#!/usr/bin/env python3
"""Validate application JSON and synchronize the browser dashboard without Node."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import (
    EXAMPLE_DATA,
    PRIVATE_DATA,
    ROOT,
    GradPilotError,
    dashboard_seed,
    load_database,
    load_profile,
    validate_database,
    write_json_atomic,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Generate ignored dashboard/data.js from local JSON, validate a dashboard "
            "export, or initialize a private working database."
        )
    )
    parser.add_argument("--data", help="Application JSON (private file wins by default)")
    parser.add_argument("--profile", help="Profile YAML (profile.private.yaml wins by default)")
    parser.add_argument(
        "--output", type=Path, default=ROOT / "dashboard" / "data.js", help="Generated JS path"
    )
    parser.add_argument("--validate-only", action="store_true", help="Validate without writing JS")
    parser.add_argument(
        "--import", dest="import_path", type=Path, help="Validate a dashboard JSON export"
    )
    parser.add_argument(
        "--write-private",
        action="store_true",
        help="With --import, atomically replace data/applications.private.json",
    )
    parser.add_argument(
        "--init-private",
        action="store_true",
        help="Create data/applications.private.json only if it does not already exist",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        if args.import_path:
            data = json.loads(args.import_path.read_text(encoding="utf-8"))
            validate_database(data)
            print(f"Valid dashboard export: {args.import_path}")
            if args.write_private:
                write_json_atomic(PRIVATE_DATA, data)
                print(f"Private database updated atomically: {PRIVATE_DATA}")
            else:
                print("Validation only; add --write-private to replace the private database.")
            return 0

        data, data_path = load_database(args.data)
        profile, profile_path = load_profile(args.profile)
        seed = dashboard_seed(data, profile, source_is_example=data_path == EXAMPLE_DATA)
        validate_database(seed)

        if args.init_private:
            if PRIVATE_DATA.exists():
                raise GradPilotError(
                    f"Refusing to overwrite existing private database: {PRIVATE_DATA}"
                )
            write_json_atomic(PRIVATE_DATA, seed)
            print(f"Initialized private database: {PRIVATE_DATA}")

        if not args.validate_only:
            # Escape HTML-sensitive characters so generated data cannot close its script tag.
            payload = json.dumps(seed, ensure_ascii=False, separators=(",", ":"))
            payload = (
                payload.replace("<", "\\u003c")
                .replace(">", "\\u003e")
                .replace("&", "\\u0026")
                .replace(" ", "\\u2028")
                .replace(" ", "\\u2029")
            )
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(
                "/* Generated by scripts/dashboard_sync.py. Ignored by Git; may contain private data. */\n"
                f"window.GRADPILOT_DATA = {payload};\n",
                encoding="utf-8",
            )
            print(f"Dashboard data synchronized: {args.output}")

        print(f"Validated {len(data['schools'])} schools from {data_path}")
        print(f"Profile: {profile_path}")
        if data_path == EXAMPLE_DATA:
            print(
                "Using public example data. Run --init-private or copy the example to "
                "data/applications.private.json before recording real information."
            )
        return 0
    except (GradPilotError, json.JSONDecodeError, OSError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
